let lang: "pt" | "en" | "es" = (() => {
  const n = (navigator.language || "en").toLowerCase();
  return n.startsWith("pt") ? "pt" : n.startsWith("es") ? "es" : "en";
})();

export function setLang(l: string): void {
  lang = l === "pt" ? "pt" : l === "es" ? "es" : "en";
  document.documentElement.lang = lang === "pt" ? "pt-BR" : lang;
  document.documentElement.setAttribute("translate", "no");          // 0.100.64: sem o tradutor do navegador
}

export function getLang(): string {
  return lang;
}

export function tr(s: string): string {
  if (lang === "pt") return s;
  const t = T[s];
  if (!t) {
    FALTAM.add(s);
    return s;
  }
  return lang === "en" ? t[0] : t[1];
}

